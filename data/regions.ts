// Signed years: BCE is negative. These are inclusive extraction windows,
// not claims that all polities in a region changed eras on the same date.
function region(id: string, name: string, subject: "japan" | "world", rows: [string, number, number][]): StudyRegion {
  return { id, name, subject, periods: rows.map(([name, start, end], i) => ({ id: `${id}-${String(i + 1).padStart(2, "0")}`, name, start, end, order: i })) };
}
